/** Settings: page address, QR code, publishing, backup and the browser draft. */
import { normalize } from '../../lib/types';
import { state, changed, discardDraft } from './state';
import { openPublish, pageUrl } from './publish';
import { h, group, navRow, dangerRow, sheet, toast } from './ui';

export function settingsTab(): HTMLElement {
  const url = pageUrl();
  return h('div', {},
    group({ header: 'Your Page' },
      navRow({ title: 'Open Page', value: url.replace(/^https?:\/\//, ''), onClick: () => open(url, '_blank') }),
      navRow({ title: 'Copy Link', onClick: async () => { await navigator.clipboard.writeText(url); toast('Link copied'); }, chevron: false }),
      navRow({ title: 'QR Code', onClick: () => sheet('QR Code', () => [h('div', { class: 'qr' },
        h('img', { src: `https://api.qrserver.com/v1/create-qr-code/?size=480x480&margin=12&data=${encodeURIComponent(url)}`, alt: 'QR code for your page' }),
        h('p', { class: 'group-f' }, 'Generated by api.qrserver.com. Right-click or long-press to save.'))]) }),
      navRow({ title: 'Publish', onClick: openPublish })),
    group({ header: 'Backup', footer: 'Your edits are kept in this browser until you publish. Export saves everything, images included, so you can continue on another device.' },
      navRow({ title: 'Export', onClick: () => {
        const a = h('a', { href: URL.createObjectURL(new Blob([JSON.stringify(state.cfg, null, 2)], { type: 'application/json' })), download: 'yourlinki.json' });
        a.click();
      } }),
      navRow({ title: 'Import', onClick: () => {
        const input = h('input', { type: 'file', accept: 'application/json', onchange: async (e: any) => {
          try { state.cfg = normalize(JSON.parse(await e.target.files[0].text())); changed(true); toast('Imported. Tap Publish to put it online.'); } catch { toast('That file is not a yourlinki backup'); }
        } });
        input.click();
      } })),
    group({ footer: 'Throws away unpublished edits in this browser and loads the page that is online now.' },
      dangerRow('Start Over from Published Page', async () => {
        if (!confirm('Discard your unpublished edits?')) return;
        await discardDraft(); toast('Loaded your published page');
      })),
    h('p', { class: 'about' }, 'yourlinki · free and open source · no account, no tracking'));
}
